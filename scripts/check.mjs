#!/usr/bin/env node
/*
 * Site consistency check. Plain Node (22+), no dependencies, no build step.
 *
 *   node scripts/check.mjs          # report problems, exit 1 if any
 *   node scripts/check.mjs --fix    # also rewrite the share meta blocks, sitemap.xml and robots.txt
 *
 * Checks that the registry (assets/js/tools.js), the folders, thumbnails, share images, page meta tags,
 * sitemap, issue templates and CDN pins all agree. Runs in CI (.github/workflows/check.yml).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://tools.tomasmartinez.xyz';
const FIX = process.argv.includes('--fix');
const { tools, categories, toolUrl, categoryUrl } = await import(pathToFileURL(join(ROOT, 'assets/js/tools.js')));

const problems = [];
const fixed = [];
const fail = (msg) => problems.push(msg);
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const exists = (p) => existsSync(join(ROOT, p));
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const unesc = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

/* ---------- Pages: every listed page, with its share image ---------- */
const listed = tools.filter((t) => t.status !== 'soon');
const pages = [
  { file: 'index.html', url: '/', og: 'default' },
  ...categories.map((c) => ({ file: `${c.id}/index.html`, url: categoryUrl(c), og: c.id, attr: ['data-category', c.id], thumbnail: c.thumbnail })),
  ...listed.map((t) => ({ file: `${toolUrl(t).slice(1)}index.html`, url: toolUrl(t), og: t.id, attr: ['data-tool', t.id], thumbnail: t.thumbnail })),
];

/* ---------- Registry ↔ folders ---------- */
const ids = new Set();
for (const x of [...categories, ...tools]) {
  if (ids.has(x.id)) fail(`Duplicate registry id "${x.id}".`);
  ids.add(x.id);
}
for (const t of tools) if (t.category && !categories.some((c) => c.id === t.category)) fail(`Tool "${t.id}" has unknown category "${t.category}".`);

for (const p of pages) {
  if (!exists(p.file)) { fail(`${p.file}: missing (registry lists ${p.url}).`); continue; }
  const html = read(p.file);
  if (p.attr && !html.includes(`${p.attr[0]}="${p.attr[1]}"`)) fail(`${p.file}: <body> needs ${p.attr[0]}="${p.attr[1]}".`);
  if (p.thumbnail && !exists(p.thumbnail.slice(1))) fail(`${p.file}: thumbnail ${p.thumbnail} not found.`);
  if (!exists(`assets/img/og/${p.og}.png`)) fail(`assets/img/og/${p.og}.png missing: run node scripts/og-images.mjs.`);
}

const SKIP_DIRS = new Set(['_template', 'assets', 'scripts', 'node_modules', '.git', '.github']);
const dirs = (p) => readdirSync(join(ROOT, p)).filter((d) => !d.startsWith('.') && !SKIP_DIRS.has(d) && statSync(join(ROOT, p, d)).isDirectory());
const pageFiles = new Set(pages.map((p) => p.file));
for (const d of dirs('.')) {
  if (exists(`${d}/index.html`) && !pageFiles.has(`${d}/index.html`) && !tools.some((t) => t.id === d && t.status === 'soon')) fail(`${d}/index.html is not in the registry.`);
  for (const sub of dirs(d)) {
    const f = `${d}/${sub}/index.html`;
    if (exists(f) && !pageFiles.has(f) && !tools.some((t) => t.id === sub && t.status === 'soon')) fail(`${f} is not in the registry.`);
  }
}

/* ---------- Meta tags: title, description, share block ---------- */
const START = '<!-- share: generated by scripts/check.mjs --fix -->';
const END = '<!-- /share -->';

function shareBlock(p, html, indent, close) {
  const title = unesc(html.match(/<title>([^<]*)<\/title>/)[1].trim());
  const description = unesc(html.match(/<meta\s+name="description"\s+content="([^"]*)"/)[1].trim());
  const url = `${SITE}${p.url}`;
  const tag = (s) => `${indent}${s}${close}`;
  return [
    `${indent}${START}`,
    tag(`<link rel="canonical" href="${url}"`),
    tag('<meta property="og:type" content="website"'),
    tag('<meta property="og:site_name" content="Toolbox"'),
    tag(`<meta property="og:title" content="${esc(title)}"`),
    tag(`<meta property="og:description" content="${esc(description)}"`),
    tag(`<meta property="og:url" content="${url}"`),
    tag(`<meta property="og:image" content="${SITE}/assets/img/og/${p.og}.png"`),
    tag('<meta property="og:image:width" content="1200"'),
    tag('<meta property="og:image:height" content="750"'),
    tag('<meta name="twitter:card" content="summary_large_image"'),
    `${indent}${END}`,
  ].join('\n');
}

for (const p of pages) {
  if (!exists(p.file)) continue;
  let html = read(p.file);
  if (!/<title>[^<]+<\/title>/.test(html)) { fail(`${p.file}: missing <title>.`); continue; }
  const desc = html.match(/<meta\s+name="description"\s+content="[^"]*"\s*\/?>/);
  if (!desc) { fail(`${p.file}: missing <meta name="description">.`); continue; }
  const indent = html.slice(html.lastIndexOf('\n', desc.index) + 1, desc.index).match(/^\s*/)[0];
  const close = desc[0].endsWith('/>') ? ' />' : '>';
  const want = shareBlock(p, html, indent, close);
  const s = html.indexOf(START), e = html.indexOf(END);
  const have = s >= 0 && e > s ? html.slice(html.lastIndexOf('\n', s) + 1, e + END.length) : null;
  if (have === want) continue;
  if (!FIX) { fail(`${p.file}: share meta block ${have ? 'is out of date' : 'is missing'} (run with --fix).`); continue; }
  html = have ? html.replace(have, want) : html.slice(0, desc.index + desc[0].length) + '\n' + want + html.slice(desc.index + desc[0].length);
  writeFileSync(join(ROOT, p.file), html);
  fixed.push(p.file);
}

// The 404 page is never indexed.
if (!/<meta name="robots" content="noindex"/.test(read('404.html'))) fail('404.html: needs <meta name="robots" content="noindex">.');

/* ---------- sitemap.xml, robots.txt ---------- */
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((p) => `  <url><loc>${SITE}${p.url}</loc></url>`).join('\n')}
</urlset>
`;
const robots = `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`;
for (const [file, want] of [['sitemap.xml', sitemap], ['robots.txt', robots]]) {
  if (exists(file) && read(file) === want) continue;
  if (FIX) { writeFileSync(join(ROOT, file), want); fixed.push(file); }
  else fail(`${file} ${exists(file) ? 'is out of date' : 'is missing'} (run with --fix).`);
}

/* ---------- Issue templates list every tool ---------- */
for (const f of ['.github/ISSUE_TEMPLATE/bug_report.yml', '.github/ISSUE_TEMPLATE/feature_request.yml']) {
  const options = new Set([...read(f).matchAll(/^\s+- (.+)$/gm)].map((m) => m[1].trim()));
  for (const t of listed) if (!options.has(t.name)) fail(`${f}: "Which tool?" is missing ${t.name}.`);
}

/* ---------- CDN pins live in cdn.js only ---------- */
const CDN = /https:\/\/(cdn\.jsdelivr\.net|esm\.sh|unpkg\.com|cdn\.sheetjs\.com)\//;
function* jsFiles(dir) {
  for (const d of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
    if (d.name.startsWith('.') || d.name === 'node_modules' || d.name === 'scripts') continue;
    const p = join(dir, d.name);
    if (d.isDirectory()) yield* jsFiles(p);
    else if (d.name.endsWith('.js') || d.name.endsWith('.mjs')) yield p;
  }
}
for (const f of jsFiles('.')) {
  const rel = relative('.', f);
  if (rel === join('assets', 'js', 'lib', 'cdn.js')) continue;
  read(rel).split('\n').forEach((line, i) => {
    if (CDN.test(line) && !/^\s*(\/\/|\*)/.test(line)) fail(`${rel}:${i + 1}: CDN URL outside assets/js/lib/cdn.js (add it to LIBS).`);
  });
}

/* ---------- Report ---------- */
if (fixed.length) console.log(`Updated ${fixed.length} file(s):\n  ${fixed.join('\n  ')}`);
if (problems.length) {
  console.error(`✗ ${problems.length} problem(s):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log(`✓ ${pages.length} pages, ${tools.length} tools, ${categories.length} categories: all consistent.`);
