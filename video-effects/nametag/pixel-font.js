export const ROWS = 8;
const glyphs = new Map();
for (const [ch, src] of Object.entries(G)) {
  const rows = src.split(' ').map((r) => [...r].map((c) => c === '#'));
  while (rows.length < ROWS) rows.push(rows[0].map(() => false));
  glyphs.set(ch, { width: rows[0].length, rows });
}

/** Rasterize a character the font doesn't have: system font at 8 px, alpha thresholded. */
const fallbackCache = new Map();
function fallbackGlyph(ch) {
  if (fallbackCache.has(ch)) return fallbackCache.get(ch);
  const c = document.createElement('canvas');
  c.width = 16; c.height = 12;
  const x = c.getContext('2d', { willReadFrequently: true });
  x.font = 'bold 9px system-ui, sans-serif';
  x.textBaseline = 'alphabetic';
  x.fillText(ch, 0, 8);
  const width = Math.max(1, Math.min(16, Math.ceil(x.measureText(ch).width)));
  const { data } = x.getImageData(0, 0, 16, 12);
  const rows = [];
  for (let r = 0; r < ROWS; r++) {
    const row = [];
    for (let col = 0; col < width; col++) row.push(data[((r + 1) * 16 + col) * 4 + 3] > 110);
    rows.push(row);
  }
  const g = { width, rows };
  fallbackCache.set(ch, g);
  return g;
}

export const glyphFor = (ch) => glyphs.get(ch) || fallbackGlyph(ch);

/** Lay out one line: glyph positions in font pixels. */
export function layoutLine(text) {
  let x = 0;
  const out = [];
  for (const ch of text) {
    const g = glyphFor(ch);
    out.push({ x, rows: g.rows });
    x += g.width + 1;
  }
  return { width: Math.max(0, x - 1), glyphs: out };
}

/** Fill the line's pixels at (x, y), each font pixel `unit` canvas px, in ctx.fillStyle. */
export function drawLine(ctx, line, x, y, unit = 1) {
  for (const g of line.glyphs) {
    g.rows.forEach((row, r) => {
      // Merge horizontal runs into one rect: fewer calls, no seams.
      let start = -1;
      for (let c = 0; c <= row.length; c++) {
        if (row[c] && start < 0) start = c;
        else if (!row[c] && start >= 0) {
          ctx.fillRect(x + (g.x + start) * unit, y + r * unit, (c - start) * unit, unit);
          start = -1;
        }
      }
    });
  }
}
